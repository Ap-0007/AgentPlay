const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const test = require('node:test')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

test('C2 is one persistent main-process task with three frozen outputs and related project artifacts', () => {
  const main = read('electron/main.js')
  const start = main.indexOf("persistentTaskRuntime.register('media.audio-repair'")
  const end = main.indexOf("persistentTaskRuntime.register('media.edit-concat'", start)
  const executor = main.slice(start, end)
  assert.ok(start > 0)
  assert.match(executor, /decision\.kind !== 'media\.repair-audio'/)
  assert.match(executor, /assertEditDecisionList\(decision\)/)
  assert.match(executor, /expectedOutputCount = decision\.audioRepair\?\.separation\?\.enabled \? 3 : 1/)
  assert.match(executor, /mediaEditService\.repairAudio/)
  assert.match(executor, /mediaEditService\.verifyAudioRepair/)
  assert.match(executor, /relatedOutputPaths: stemPaths/)
  assert.match(main, /decision\.kind === 'media\.repair-audio'[\s\S]{0,100}'media\.audio-repair'/)
  assert.match(main, /decision\.kind === 'media\.repair-audio'[\s\S]{0,300}plannedOutputs/)
})

test('C2 renderer exposes local progress and never hides the separation artifact warning', () => {
  const panel = read('src/components/agent-panel/useMediaCreativeTasks.ts')
  const runtime = read('src/components/agent-panel/usePersistentTaskRuntime.ts')
  const router = read('src/components/agent-panel/intentRouter.ts')
  const types = read('src/types/global.d.ts')
  const projects = read('electron/media-edit-project-store.js')
  assert.match(panel, /decision\.kind === 'media\.repair-audio' \? 'audio-repair'/)
  assert.match(panel, /专业音频修复与基础分离/)
  assert.match(panel, /带伪影说明的基础人声\/伴奏轨/)
  assert.match(panel, /'media\.mix-audio', 'media\.repair-audio', 'media\.visual-effects'/)
  assert.match(runtime, /runtimeTask\.type === 'media\.audio-repair'/)
  assert.match(router, /降噪\|去直流\|响度匹配\|静音修复\|分离人声\|提取伴奏/)
  assert.match(types, /strategy: 'ffmpeg-audio-repair-v1'/)
  assert.match(projects, /decision\?\.kind === 'media\.repair-audio'\) return 'repair-audio'/)
})

test('C2 quality gate requires repair evidence and non-AI separation claims', () => {
  const quality = read('electron/task-result-quality.js')
  for (const code of ['AUDIO_REPAIR_PROOF_MISSING', 'DENOISE_NOT_IMPROVED', 'DC_NOT_IMPROVED', 'SILENCE_REPAIR_MISMATCH', 'SEPARATION_PROOF_MISSING', 'SEPARATION_WARNING_MISSING']) assert.match(quality, new RegExp(code))
  assert.match(quality, /taskType === 'media\.audio-repair'/)
  assert.match(quality, /decoded-audio-repair-v1/)
  assert.match(quality, /stereo-mid-side-v1/)
})

test('C2 has an installed conversation acceptance with three outputs, quality 100 and visible limitations', () => {
  const smokePath = path.join(root, 'scripts', 'smoke-packaged-audio-repair.mjs')
  assert.equal(fs.existsSync(smokePath), true)
  const smoke = read('scripts/smoke-packaged-audio-repair.mjs')
  assert.match(smoke, /media\.audio-repair/)
  assert.match(smoke, /quality\?\.score !== 100/)
  assert.match(smoke, /outputs\?\.length !== 3/)
  assert.match(smoke, /不恢复丢失语音/)
  assert.match(smoke, /不是AI专业分轨/)
  assert.match(smoke, /JSON\.stringify\(before\) !== JSON\.stringify\(after\)/)
})
